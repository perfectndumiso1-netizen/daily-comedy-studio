"""Command-line entry point for one-off video generation."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

from .scenarios import available_categories, choose_scenario
from .video import create_video, validate_video

METHOD = "Offline original 2D motion graphics: Pillow-drawn scenes + locally synthesized audio + FFmpeg H.264/AAC. No generative AI video or external media is used."
LICENSE_NOTES = "All artwork, scenario text, captions, and audio are generated by this project at runtime; no third-party footage, music, or stock assets are bundled. Caption text uses the runner's DejaVu Sans system font when available, or Pillow's built-in fallback; no font is distributed as a separate asset."


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Create one original, captioned vertical comedy MP4.")
    parser.add_argument("--output", default="output/comedy.mp4", help="MP4 destination (default: output/comedy.mp4)")
    parser.add_argument("--report", default=None, help="Scenario text report destination (default: beside MP4 as scenario.txt)")
    parser.add_argument("--history", default="output/history.json", help="Recent-concept history JSON (default: output/history.json)")
    parser.add_argument("--category", default="random", choices=["random", *available_categories()], help="Scenario category")
    parser.add_argument("--seed", type=int, default=None, help="Optional seed for repeatable local testing")
    parser.add_argument("--fps", type=int, default=24, help="Frame rate, 1–30 (default: 24)")
    parser.add_argument("--seconds-per-scene", type=float, default=3.0, help="Duration per scene (default: 3s; video totals 4 scenes)")
    parser.add_argument("--validate", metavar="MP4", help="Validate an existing MP4 and exit")
    return parser


def write_report(scenario: dict, path: Path, metadata: dict) -> None:
    lines = [
        f"Daily Comedy Studio — {scenario['title']}",
        f"Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"Category: {scenario['category']}",
        f"Concept ID: {scenario['id']}",
        f"Generation method: {METHOD}",
        "",
        "SCENES AND EMBEDDED CAPTIONS (the captions are burned into the video):",
    ]
    for number, scene in enumerate(scenario["scenes"], start=1):
        lines.extend([f"{number}. {scene['caption']}", f"   Visual: {scene['description']}"])
    lines.extend([
        "", "VIDEO VALIDATION:",
        f"Resolution: {metadata['width']} x {metadata['height']} px",
        f"Frame rate: {metadata['fps']} fps", f"Duration: {metadata['duration']:.1f} seconds",
        f"Video/audio: {metadata['video_codec']} / {metadata['audio_codec']}",
        "", "ASSET AND LICENSING NOTES:", LICENSE_NOTES,
        "Audio is original, quiet synthesized instrumental/chime effects; there is no speech or voice-over.",
        "The script is an original short-form scenario from the included project library, not copied from another creator.",
        "", "This is illustrated motion graphics, not photorealistic footage or a generative-video model.",
    ])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.validate:
            info = validate_video(args.validate)
            print("Valid playable MP4:", info)
            return 0
        output = Path(args.output)
        scenario, _ = choose_scenario(args.history, args.category, args.seed)
        print(f"Selected: {scenario['title']} [{scenario['category']}]")
        print("Rendering 720x1280 H.264/AAC video; no external API or media download...")
        create_video(scenario, output, args.fps, args.seconds_per_scene)
        metadata = validate_video(output)
        report_path = Path(args.report) if args.report else output.with_name("scenario.txt")
        write_report(scenario, report_path, metadata)
        print(f"Created: {output} ({output.stat().st_size:,} bytes)")
        print(f"Scenario report: {report_path}")
        print(f"Validation: {metadata}")
        return 0
    except (OSError, ValueError, RuntimeError) as exc:
        print(f"ERROR: comedy video generation failed: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
